def main() -> None:
    idx_path = ROOT / "index.json"
    idx = json.loads(idx_path.read_text(encoding="utf-8"))
    have = {t["id"] for t in idx["templates"]}
    have_series = {s["id"] for s in idx.get("series", [])}
    added = 0
    for tid, mode, title, desc, clothing, scene, action in M:
        src = DRAFT / f"{tid}.png"
        if not src.is_file():
            print(f"!! {tid} 底片不存在，跳过")
            continue
        shutil.copy2(src, TPL / f"{tid}.png")
        if tid in have:
            continue
        idx["templates"].append({
            "id": tid, "series": tid, "mode": mode, "title": title,
            "file": f"templates/{tid}.png", "desc": desc,
            "components": {"服装": clothing, "场景": scene, "妆容": "自然清透", "动作": action},
        })
        if tid not in have_series:
            idx.setdefault("series", []).append(
                {"id": tid, "mode": mode, "title": title.split(" · ")[0], "variants": [tid]})
        added += 1
    idx_path.write_text(json.dumps(idx, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"新增 {added} 张，库共 {len(idx['templates'])} 张模板 / {len(idx.get('series', []))} 个系列")


if __name__ == "__main__":
    main()
